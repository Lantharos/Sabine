use accesskit::Role;

use crate::osr::protocol::accessibility::{AxNode, attribute, state};

/// The role assistive technology knows a page node by, from Chromium's name
/// for it and, for text fields, what they take.
pub(super) fn role(node: &AxNode) -> Role {
    if node.has_state(state::IGNORED) || node.has_state(state::INVISIBLE) {
        return Role::GenericContainer;
    }
    match node.role.as_str() {
        "textField" => text_field_role(node),
        "genericContainer" | "none" | "section" | "sectionWithoutName" | "paragraph"
            if node.flag(attribute::TEXT_FIELD_ROOT) =>
        {
            if node.has_state(state::MULTILINE) {
                Role::MultilineTextInput
            } else {
                Role::TextInput
            }
        }
        name => chromium_role(name),
    }
}

fn text_field_role(node: &AxNode) -> Role {
    if node.has_state(state::PROTECTED) {
        return Role::PasswordInput;
    }
    if node.has_state(state::MULTILINE) {
        return Role::MultilineTextInput;
    }
    match node.string(attribute::INPUT_TYPE).unwrap_or_default() {
        "email" => Role::EmailInput,
        "number" => Role::NumberInput,
        "tel" => Role::PhoneNumberInput,
        "url" => Role::UrlInput,
        "week" => Role::WeekInput,
        "month" => Role::MonthInput,
        _ => Role::TextInput,
    }
}


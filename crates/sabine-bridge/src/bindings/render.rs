use std::borrow::Cow;
use std::collections::{BTreeMap, HashSet};

use specta::Types;
use specta::datatype::{DataType, Fields, NamedDataType, NamedReferenceType, Reference};
use specta_typescript::{Exporter, FrameworkExporter, Typescript};

use super::BridgeBindings;
use super::numbers::JsonNumbers;
use super::walk::walk;

const PRELUDE: &str = "// Generated by Sabine from the app's bridge commands and events. Run `sabine bindings` after changing them.";

enum Params {
    None,
    Inline(DataType),
    Named(DataType),
}

struct Command {
    name: String,
    params: Params,
    result: DataType,
}

struct Event {
    name: &'static str,
    payload: DataType,
}

type TypeKey = (Cow<'static, str>, Cow<'static, str>);

pub(super) fn render(bindings: &BridgeBindings) -> Result<String, String> {
    let mut types = Types::default();
    let mut inlined = HashSet::new();
    let commands = bindings
        .commands
        .iter()
        .map(|(name, signature)| {
            let params = (signature.params)(&mut types);
            let result = (signature.result)(&mut types);
            Command {
                name: name.clone(),
                params: params_of(params, &types, &mut inlined),
                result,
            }
        })
        .collect::<Vec<_>>();
    let events = bindings
        .events
        .iter()
        .map(|(name, payload)| Event {
            name,
            payload: payload(&mut types),
        })
        .collect::<Vec<_>>();
    unique_keys(
        commands.iter().map(|command| command.name.as_str()),
        "command",
    )?;
    unique_keys(events.iter().map(|event| event.name), "event")?;

    let referenced = referenced(&types, &commands, &events);
    types.iter_mut(|named| {
        if inlined.contains(&key(named)) && !referenced.contains(&key(named)) {
            named.ty = None;
        }
    });

    Exporter::from(Typescript::new())
        .framework_prelude(PRELUDE)
        .framework_runtime(move |exporter| runtime(&exporter, &commands, &events).map(Cow::Owned))
        .export(&types, JsonNumbers)
        .map_err(|error| error.to_string())
}

fn params_of(dt: DataType, types: &Types, inlined: &mut HashSet<TypeKey>) -> Params {
    let named = match &dt {
        DataType::Reference(Reference::Named(reference)) => types
            .get(reference)
            .filter(|named| named.generics.is_empty()),
        _ => None,
    };
    let Some((named, ty)) = named.and_then(|named| Some((named, named.ty.clone()?))) else {
        return Params::Named(dt);
    };
    inlined.insert(key(named));
    match &ty {
        DataType::Struct(structure) if has_no_fields(&structure.fields) => Params::None,
        _ => Params::Inline(ty),
    }
}

fn has_no_fields(fields: &Fields) -> bool {
    match fields {
        Fields::Unit => true,
        Fields::Unnamed(_) => false,
        Fields::Named(fields) => fields.fields.is_empty(),
    }
}

fn key(named: &NamedDataType) -> TypeKey {
    (named.module_path.clone(), named.name.clone())
}

fn referenced(types: &Types, commands: &[Command], events: &[Event]) -> HashSet<TypeKey> {
    let mut roots = types
        .into_unsorted_iter()
        .filter_map(|named| named.ty.clone())
        .collect::<Vec<_>>();
    for command in commands {
        roots.push(command.result.clone());
        if let Params::Inline(dt) | Params::Named(dt) = &command.params {
            roots.push(dt.clone());
        }
    }
    roots.extend(events.iter().map(|event| event.payload.clone()));

    let mut referenced = HashSet::new();
    for root in &mut roots {
        walk(root, &mut |dt| {
            if let DataType::Reference(Reference::Named(reference)) = dt
                && let NamedReferenceType::Reference { .. } = reference.inner
                && let Some(named) = types.get(reference)
            {
                referenced.insert(key(named));
            }
        });
    }
    referenced
}

fn runtime(
    exporter: &FrameworkExporter,
    commands: &[Command],
    events: &[Event],
) -> Result<String, specta_typescript::Error> {
    let imports = [
        (!commands.is_empty()).then_some("invoke"),
        (!events.is_empty()).then_some("listen"),
        (!commands.is_empty()).then_some("type InvokeOptions"),
    ];
    let imports = imports.into_iter().flatten().collect::<Vec<_>>();
    if imports.is_empty() {
        return Ok(String::new());
    }
    let mut out = format!(
        "import {{ {} }} from \"@lantharos/sabine\";\n",
        imports.join(", ")
    );

    if !commands.is_empty() {
        out.push_str("\nexport const commands = {\n");
        for command in commands {
            let name = quoted(&command.name);
            let result = exporter.reference(&command.result)?;
            let (params, value) = match &command.params {
                Params::None => (String::new(), "{}"),
                Params::Inline(dt) => (
                    format!("params: {}, ", exporter.inline(dt)?.replace('\n', "\n\t")),
                    "params",
                ),
                Params::Named(dt) => (format!("params: {}, ", exporter.reference(dt)?), "params"),
            };
            out.push_str(&format!(
                "\t{}: ({params}options?: InvokeOptions) => invoke<{result}>({name}, {value}, options),\n",
                camel_case(&command.name)
            ));
        }
        out.push_str("};\n");
    }

    if !events.is_empty() {
        out.push_str("\nexport const events = {\n");
        for event in events {
            let payload = exporter.reference(&event.payload)?;
            out.push_str(&format!(
                "\t{}: (callback: (payload: {payload}) => void) => listen<{payload}>({}, callback),\n",
                camel_case(event.name),
                quoted(event.name)
            ));
        }
        out.push_str("};\n");
    }
    Ok(out)
}

fn unique_keys<'a>(names: impl Iterator<Item = &'a str>, kind: &str) -> Result<(), String> {
    let mut keys = BTreeMap::new();
    for name in names {
        if let Some(other) = keys.insert(camel_case(name), name) {
            return Err(format!(
                "the {kind}s `{other}` and `{name}` both become `{}` in TypeScript",
                camel_case(name)
            ));
        }
    }
    Ok(())
}

fn camel_case(name: &str) -> String {
    name.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .enumerate()
        .flat_map(|(index, part)| {
            let mut chars = part.chars();
            let first = chars.next().map(|first| match index {
                0 => first.to_ascii_lowercase(),
                _ => first.to_ascii_uppercase(),
            });
            first.into_iter().chain(chars)
        })
        .collect()
}

fn quoted(name: &str) -> String {
    serde_json::Value::from(name).to_string()
}
